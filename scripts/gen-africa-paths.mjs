// Generates components/africa/africaPaths.ts from public/images/africa.svg.
// Run: node scripts/gen-africa-paths.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const svg = readFileSync(join(root, "public/images/africa.svg"), "utf8");

const blocks = svg.match(/<path\b[\s\S]*?\/>/g) ?? [];
const entries = [];
for (const b of blocks) {
  const d = b.match(/\bd="([^"]*)"/)?.[1];
  const id = b.match(/\bid="([^"]*)"/)?.[1];
  const title = b.match(/\btitle="([^"]*)"/)?.[1] ?? id;
  if (!d || !id) continue;
  entries.push({ id: id.toUpperCase(), title, d: d.trim() });
}
entries.sort((a, b) => a.title.localeCompare(b.title));

const viewBox =
  svg.match(/\bviewBox="([^"]*)"/)?.[1] ?? "0 0 239.05701 217.31789";

const out = `// AUTO-GENERATED by scripts/gen-africa-paths.mjs from public/images/africa.svg.
// Do not edit by hand — edit the SVG and re-run the script.
// One entry per African country/territory, id = ISO 3166-1 alpha-2.

export interface AfricaCountryPath {
  id: string;
  title: string;
  d: string;
}

export const AFRICA_VIEWBOX = ${JSON.stringify(viewBox)};

export const AFRICA_PATHS: AfricaCountryPath[] = ${JSON.stringify(entries, null, 2)};
`;

writeFileSync(join(root, "components/africa/africaPaths.ts"), out);
console.log(`Wrote ${entries.length} country paths to components/africa/africaPaths.ts`);
